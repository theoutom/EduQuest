import assert from 'node:assert/strict';
import { Browser } from './http-client.mjs';

const student = new Browser();
const peer = new Browser();
const admin = new Browser();
await student.login('satrio');
await peer.login('nadia');
await admin.login('operator');
await student.visit('/kuis/sql-relasional');
await peer.visit('/kuis');
await admin.visit('/admin/kuis');
const accept = { accept: 'application/json' };
const start = await student.visit('/kuis/sql-relasional/mulai', {});
const exam = start.response.headers.get('location');
assert.match(exam, /^\/sesi\/\d+$/);
assert.equal((await student.visit(exam + '/tutor', { position: '1', intent: 'mulai' }, accept)).response.status, 403);
const draft = await admin.visit('/admin/kuis', { action: 'create', slug: 'tutor-latihan', title: 'Latihan Tutor', summary: 'Latihan konsep.', topic: 'pemrograman', level: 'dasar', attempt_limit: '3', minutes: '5', passing: '60', tutor_enabled: '1' });
assert.equal(draft.response.status, 303);
const edit = draft.response.headers.get('location').split('?')[0];
const editor = await admin.visit(edit);
const draftId = editor.text.match(/name="draft_id" value="(\d+)"/)[1];
const privateStem = 'Modulus 98 dan 13 untuk soal unik TUTORPRIVATE';
assert.equal((await admin.visit(edit, { action: 'question-save', draft_id: draftId, stem: privateStem, a: 'RAHASIAOPSI', b: 'Salah', correct: 'a', explanation: 'RAHASIAKUNCI' })).response.status, 303);
assert.equal((await admin.visit(edit, { action: 'publish', draft_id: draftId })).response.status, 303);
const practice = (await student.visit('/kuis/tutor-latihan/mulai', {})).response.headers.get('location');
const practicePage = await student.visit(practice);
assert.match(practicePage.text, /Tutor latihan/);
const question = practicePage.text.match(/name="question" value="(\d+)"/)[1];
const option = practicePage.text.match(/name="option" value="(\d+)"/)[1];
const nativeOpen = await student.visit(practice + '/jawaban', { question, option, doubtful: '1', target: 'tutor', position: '1' });
assert.equal(nativeOpen.response.headers.get('location'), practice + '/tutor?soal=1', 'Native navigation saves the current answer and opens Tutor');
assert.match((await student.visit(practice)).text, /name="doubtful" value="1" checked/);
assert.doesNotMatch((await student.visit(exam)).text, /data-tutor-open/);
assert.equal((await peer.visit(practice + '/tutor', { position: '1', intent: 'mulai' }, accept)).response.status, 404);
assert.equal((await student.visit(practice + '/tutor', { position: '1', intent: 'berikan-kunci' }, accept)).response.status, 422);
assert.equal((await student.visit(practice + '/tutor', { position: '1', intent: 'mulai', csrf: '' }, accept)).response.status, 403);
const hint = await student.visit(practice + '/tutor', { position: '1', intent: 'mulai' }, accept);
assert.equal(hint.response.status, 200);
const guidance = JSON.parse(hint.text);
assert.match(guidance.hint, /sisa|pembagian|pembagi/i);
const offline = process.env.EDUQUEST_TEST_TUTOR_FALLBACK === '1';
assert.equal(guidance.source, offline ? 'panduan' : (process.env.EDUQUEST_TEST_9ROUTER === '1' ? '9router' : 'ollama'));
assert.match(guidance.prompt, offline ? /langkah pertama/ : /contoh kecil/);
assert.doesNotMatch(hint.text, /TUTORPRIVATE|RAHASIAOPSI|RAHASIAKUNCI|98/);
const plain = await student.visit(practice + '/tutor?soal=1');
assert.match(plain.text, /Pilih jenis bantuan/);
const noScript = await student.visit(practice + '/tutor', { position: '1', intent: 'contoh' });
assert.equal(noScript.response.status, 200);
assert.match(noScript.text, /Panduan bawaan/);
assert.doesNotMatch(noScript.text, /PRIVATEOUTPUT|RAHASIAKUNCI/);
for (let count = 0; count < 6; count++) {
  const answer = await student.visit(practice + '/tutor', { position: '1', intent: 'contoh' }, accept);
  assert.equal(answer.response.status, 200);
  assert.equal(JSON.parse(answer.text).source, 'panduan');
  assert.doesNotMatch(answer.text, /PRIVATEOUTPUT/);
}
assert.equal((await student.visit(practice + '/tutor', { position: '1', intent: 'mulai' }, accept)).response.status, 429);
assert.equal((await student.visit(practice + '/kumpulkan', {})).response.status, 303);
assert.equal((await student.visit(practice + '/tutor', { position: '1', intent: 'mulai' }, accept)).response.status, 409);
console.log('PASS: tutor ownership, mode, CSRF, provider contract, fallback, usage limit and finalization');
