import assert from 'node:assert/strict';
import { Browser } from './http-client.mjs';

const admin = new Browser();
const teacher = new Browser();
const student = new Browser();
const other = new Browser();
await Promise.all([admin.login('operator'), teacher.login('guru-uji'), other.login('nadia')]);
await Promise.all([admin.visit('/admin'), teacher.visit('/guru'), other.visit('/')]);
const studentCreated = await admin.visit('/admin/siswa', {
  action: 'create', username: 'murid-minigame', name: 'Murid Minigame', password: process.env.EDUQUEST_TEST_PASSWORD,
});
assert.equal(studentCreated.response.status, 303);
const studentPath = studentCreated.response.headers.get('location').replace(/\?saved=1$/, '');
assert.match(studentPath, /^\/admin\/siswa\/\d+$/);
const studentId = studentPath.split('/').at(-1);
await student.login('murid-minigame');
await student.visit('/');
const created = await admin.visit('/admin/kelas', { action: 'create', name: 'Mini B', year: '2026/2027' });
assert.equal(created.response.status, 303);
const classPath = created.response.headers.get('location').replace(/\?saved=1$/, '');
const classId = classPath.split('/').at(-1);
const page = (await admin.visit(classPath)).text;
const teacherId = page.match(/Guru Uji[\s\S]*?name="teacher_id" value="(\d+)"/)[1];
assert.equal((await admin.visit(classPath, { action: 'assign-teacher', teacher_id: teacherId })).response.status, 303);
assert.equal((await admin.visit(classPath, { action: 'assign', student_id: studentId })).response.status, 303);
const game = { action: 'create', title: 'Susun langkah B', instruction: 'Urutkan.', explanation: 'Penjelasan.', steps: 'Pertama\nKedua\nKetiga', class_id: classId, xp: '30' };
assert.equal((await teacher.visit('/guru/minigame', { ...game, class_id: '0' })).response.status, 403);
assert.equal((await teacher.visit('/guru/minigame', game)).response.status, 303);
const management = (await teacher.visit('/guru/minigame')).text;
const gameId = management.match(/Susun langkah B[\s\S]*?name="game_id" value="(\d+)"/)[1];
assert.equal((await other.visit('/minigame/' + gameId)).response.status, 404);
const play = (await student.visit('/minigame/' + gameId)).text;
assert.doesNotMatch(play, /Penjelasan\./);
const submission = play.match(/name="submission" value="([a-f0-9]{32})"/)[1];
const token = text => play.match(new RegExp('<option value="([a-f0-9]{32})"[^>]*>' + text + '</option>'))[1];
const order = ['Pertama', 'Kedua', 'Ketiga'].map(token);
const encoded = steps => Object.fromEntries(steps.map((value, index) => [`order[${index}]`, value]));
assert.equal((await student.visit('/minigame/' + gameId, { submission, ...encoded([order[0], order[0], order[2]]) })).response.status, 422);
const completed = await student.visit('/minigame/' + gameId, { submission, ...encoded(order) });
assert.doesNotMatch((await admin.visit(studentPath)).text, /Hapus akun siswa/, 'Student with game history has no delete action');
assert.equal(completed.response.status, 303);
const account = await admin.visit(studentPath);
assert.match(account.text, /0 percobaan kuis/);
assert.match(account.text, /0 pemesanan mentor/);
assert.equal((await admin.visit(studentPath, { action: 'delete', confirm: '1' })).response.status, 409, 'Student with only minigame history cannot be deleted');
const resultPath = completed.response.headers.get('location');
const result = await student.visit(resultPath);
assert.match(result.text, /Urutan benar/);
assert.match(result.text, /Penjelasan\./);
assert.match(result.text, /30 XP/);
assert.equal((await other.visit(resultPath)).response.status, 404);
assert.equal((await student.visit('/minigame/' + gameId, { submission, ...encoded(order) })).response.headers.get('location'), resultPath);
assert.equal((await admin.visit(classPath, { action: 'remove', student_id: studentId })).response.status, 303);
assert.equal((await student.visit('/minigame/' + gameId)).response.status, 404);
assert.equal((await student.visit(resultPath)).response.status, 200);
console.log('PASS: minigame authoring, class authorization, scoring, retry and private results over HTTP');
