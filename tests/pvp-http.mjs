import assert from 'node:assert/strict';
import { setTimeout as delay } from 'node:timers/promises';
import { Browser } from './http-client.mjs';

const admin = new Browser(), alice = new Browser(), bob = new Browser();
await Promise.all([admin.login('operator'), alice.login('satrio'), bob.login('nadia')]);
await admin.visit('/admin/kelas');
const created = await admin.visit('/admin/kelas', { action: 'create', name: 'PvP HTTP', year: '2026/2027' });
assert.equal(created.response.status, 303);
const classPath = created.response.headers.get('location').replace(/\?saved=1$/, '');
const classId = classPath.split('/').at(-1);
for (const student_id of ['1', '2']) assert.equal((await admin.visit(classPath, { action: 'assign', student_id })).response.status, 303);
assert.equal((await admin.visit('/arena')).response.status, 403);
assert.equal((await alice.visit('/arena')).response.status, 200);
const invitation = await alice.visit('/arena', { action: 'invite', class_id: classId, opponent: '2', quiz_id: '1' });
assert.equal(invitation.response.status, 303);
const match = invitation.response.headers.get('location');
assert.doesNotMatch((await admin.visit('/admin/siswa/1')).text, /Hapus akun siswa/, 'Student with match history has no delete action');
assert.equal((await admin.visit('/admin/siswa/1', { action: 'delete', confirm: '1' })).response.status, 409, 'Student with match history cannot be deleted');
const pending = await bob.visit(match);
assert.match(pending.text, /Terima dan mulai/);
assert.doesNotMatch(pending.text, /Jika nilai x = 14/);
assert.equal((await bob.visit(match, { action: 'accept', csrf: 'invalid' })).response.status, 403);
assert.equal((await bob.visit(match, { action: 'accept' })).response.status, 303);
assert.doesNotMatch((await alice.visit(match)).text, /Jika nilai x = 14/);
await delay(13000);
const open = await alice.visit(match);
assert.match(open.text, /Jika nilai x = 14/);
assert.doesNotMatch(open.text, /Operator % mengembalikan sisa pembagian/);
const question = open.text.match(/name="question" value="(\d+)"/)[1];
const first = open.text.match(/name="option" value="(\d+)"/)[1];
assert.equal((await alice.visit(match, { action: 'answer', question, option: first })).response.status, 303);
assert.equal((await alice.visit(match, { action: 'answer', question, option: first })).response.status, 303);
assert.equal((await alice.visit(match, { action: 'finish' })).response.status, 303);
assert.doesNotMatch((await alice.visit(match)).text, /Hasil pertandingan|Operator % mengembalikan sisa pembagian/);
assert.doesNotMatch((await bob.visit(match)).text, /Hasil pertandingan|Operator % mengembalikan sisa pembagian/);
assert.equal((await bob.visit(match, { action: 'finish' })).response.status, 303);
assert.match((await alice.visit(match)).text, /Hasil pertandingan[\s\S]*Operator % mengembalikan sisa pembagian/);
assert.match((await bob.visit(match)).text, /Hasil pertandingan[\s\S]*Operator % mengembalikan sisa pembagian/);
const pending2 = await alice.visit('/arena', { action: 'invite', class_id: classId, opponent: '2', quiz_id: '1' });
const match2 = pending2.response.headers.get('location');
assert.equal((await admin.visit(classPath, { action: 'remove', student_id: '2' })).response.status, 303);
assert.equal((await alice.visit(match2)).response.status, 404);
assert.doesNotMatch((await alice.visit('/arena')).text, new RegExp(`href="${match2}"`));
assert.equal((await bob.visit(match)).response.status, 200);
console.log('PASS: PvP HTTP invitation, synchronized round, CSRF, privacy, completion and revoked class.');
