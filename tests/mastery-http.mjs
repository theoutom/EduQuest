import assert from 'node:assert/strict';
import { Browser } from './http-client.mjs';

const admin = new Browser(), teacher = new Browser(), student = new Browser(), peer = new Browser();
await Promise.all([admin.login('operator'), teacher.login('guru-uji'), student.login('satrio'), peer.login('nadia')]);
await admin.visit('/admin/kelas');
await teacher.visit('/guru/kuis');
const created = await admin.visit('/admin/kelas', { action: 'create', name: 'Mastery HTTP', year: '2026/2027' });
assert.equal(created.response.status, 303);
const classPath = created.response.headers.get('location').replace(/\?saved=1$/, '');
const classId = classPath.split('/').at(-1);
const classPage = await admin.visit(classPath);
const teacherId = classPage.text.match(/Guru Uji[\s\S]*?name="teacher_id" value="(\d+)"/)[1];
assert.equal((await admin.visit(classPath, { action: 'assign-teacher', teacher_id: teacherId })).response.status, 303);
assert.equal((await admin.visit(classPath, { action: 'assign', student_id: '1' })).response.status, 303);
const quiz = await teacher.visit('/guru/kuis', { action: 'create', slug: 'mastery-http', title: 'Kuis Mastery HTTP', summary: 'Latihan', topic: 'pemrograman', level: 'dasar', attempt_limit: '3', minutes: '5', passing: '60', class_id: classId });
assert.equal(quiz.response.status, 303);
const quizPath = quiz.response.headers.get('location').replace(/\?saved=1$/, '');
const quizId = quizPath.split('/').at(-1);
const draft = (await teacher.visit(quizPath)).text.match(/name="draft_id" value="(\d+)"/)[1];
assert.equal((await teacher.visit(quizPath, { action: 'question-save', draft_id: draft, stem: 'Berapa 2 + 2?', a: '4', b: '5', correct: 'a', explanation: 'Dua ditambah dua adalah empat.' })).response.status, 303);
assert.equal((await teacher.visit(quizPath, { action: 'publish', draft_id: draft })).response.status, 303);
assert.equal((await admin.visit('/admin/mastery')).response.status, 200);
assert.equal((await admin.visit('/admin/mastery', { action: 'save', title: 'Prasyarat global', description: 'Untuk semua', topic: 'pemrograman', quiz_id: '0', class_id: '0' })).response.status, 303);
const teacherMastery = await teacher.visit('/guru/mastery');
assert.equal(teacherMastery.response.status, 200);
assert.match(teacherMastery.text, /name="prerequisites\[\]"[^>]*> Prasyarat global/);
assert.doesNotMatch(teacherMastery.text, /<summary>Prasyarat global/);
const node = { action: 'save', title: 'Kompetensi HTTP', description: 'Memahami penjumlahan', topic: 'pemrograman', quiz_id: quizId, class_id: classId };
assert.equal((await teacher.visit('/guru/mastery', { ...node, class_id: '0' })).response.status, 403);
assert.equal((await teacher.visit('/guru/mastery', node)).response.status, 303);
const management = await teacher.visit('/guru/mastery');
const nodeId = management.text.match(/name="node_id" value="(\d+)"/)[1];
assert.equal((await teacher.visit('/guru/mastery', { ...node, node_id: nodeId, description: 'Deskripsi diperbarui' })).response.status, 303);
assert.match((await teacher.visit('/guru/mastery')).text, /versi 2/);
assert.match((await student.visit('/mastery')).text, /Kompetensi HTTP[\s\S]*Nilai lulus kompetensi: 60/);
assert.doesNotMatch((await peer.visit('/mastery')).text, /Kompetensi HTTP/);
const start = await student.visit('/kuis/mastery-http/mulai', {});
assert.equal(start.response.status, 303);
const session = start.response.headers.get('location');
const exercise = await student.visit(session);
const question = exercise.text.match(/name="question" value="(\d+)"/)[1];
const option = exercise.text.match(/name="option" value="(\d+)"/)[1];
assert.equal((await student.visit(session + '/jawaban', { question, option, position: '1', target: '1' })).response.status, 303);
assert.equal((await student.visit(session + '/kumpulkan', {})).response.status, 303);
assert.match((await student.visit('/mastery')).text, /Dikuasai[\s\S]*Kompetensi HTTP/);
assert.equal((await teacher.visit('/guru/mastery', { ...node, title: 'Perlu versi baru' })).response.status, 303);
assert.equal((await teacher.visit(quizPath, { action: 'draft' })).response.status, 303);
const newDraft = (await teacher.visit(quizPath)).text.match(/name="draft_id" value="(\d+)"/)[1];
assert.equal((await teacher.visit(quizPath, { action: 'publish', draft_id: newDraft })).response.status, 303);
assert.match((await teacher.visit('/guru/mastery')).text, /Kuis memiliki versi baru/);
assert.equal((await admin.visit(classPath, { action: 'assign', student_id: '2' })).response.status, 303);
assert.match((await peer.visit('/mastery')).text, /Kuis telah diperbarui/);
assert.equal((await admin.visit(classPath, { action: 'remove', student_id: '1' })).response.status, 303);
assert.doesNotMatch((await student.visit('/mastery')).text, /Kompetensi HTTP/);
console.log('PASS: teacher creates mastery for an assigned class, and only a passing class member earns it.');
