import assert from 'node:assert/strict';
import { Browser } from './http-client.mjs';

const author = new Browser();
const learner = new Browser();
const admin = new Browser();
await author.login('satrio');
await learner.login('nadia');
await admin.login('operator');
await author.visit('/komunitas');
await learner.visit('/komunitas');
await admin.visit('/admin');
const form = { action: 'create', title: 'Latihan OOP', topic: 'pemrograman', level: 'dasar', stem: 'Apa itu enkapsulasi?', a: 'Menyembunyikan rincian', b: 'Menghapus kelas', correct: 'a', explanation: 'Akses diatur melalui antarmuka publik.' };
const posted = await author.visit('/komunitas', form);
assert.equal(posted.response.status, 303, 'Students can submit a question to moderation');
const link = posted.response.headers.get('location');
const id = link.match(/\/komunitas\/(\d+)/)[1];
const path = '/komunitas/' + id;
assert.equal((await learner.visit(path)).response.status, 404);
assert.equal((await learner.visit(path + '/tutor')).response.status, 404);
assert.doesNotMatch((await learner.visit('/komunitas')).text, /Latihan OOP/);
assert.equal((await learner.visit('/admin/komunitas')).response.status, 403);
assert.equal((await admin.visit('/admin/komunitas/' + id, { action: 'publish', csrf: '' })).response.status, 403);
const moderation = '/admin/komunitas/' + id;
const previous = await admin.visit(moderation);
const revisionOf = page => page.text.match(/name="revision" value="(\d+)"/)[1];
assert.match(previous.text, /Latihan OOP/);
assert.equal((await author.visit(path, { ...form, action: 'update', stem: 'Apa yang dimaksud enkapsulasi?' })).response.status, 303);
assert.equal((await admin.visit(moderation, { action: 'publish', revision: revisionOf(previous) })).response.status, 409, 'Moderation cannot approve an unseen revision');
assert.equal((await admin.visit(moderation, { action: 'publish', revision: revisionOf(await admin.visit(moderation)) })).response.status, 303);
assert.match((await learner.visit('/komunitas?q=latihan&topik=pemrograman&level=dasar')).text, /Latihan OOP/);
assert.doesNotMatch((await learner.visit(path)).text, /Akses diatur melalui antarmuka publik/);
assert.equal((await learner.visit(path, { action: 'answer', choice: 'z' })).response.status, 422);
assert.equal((await learner.visit(path, { action: 'answer', choice: 'a' })).response.status, 303);
assert.match((await learner.visit(path)).text, /Akses diatur melalui antarmuka publik/);
for (let i = 0; i < 2; i++) assert.equal((await learner.visit(path, { action: 'vote' })).response.status, 303);
assert.match((await learner.visit(path)).text, /1 suara/);
assert.equal((await learner.visit(path, { action: 'comment', body: 'Soal <uji> menarik.' })).response.status, 303);
const detail = await learner.visit(path);
assert.match(detail.text, /Soal &lt;uji&gt; menarik/);
assert.doesNotMatch(detail.text, /Soal <uji>/);
const commentId = detail.text.match(/name="comment_id" value="(\d+)"/)[1];
assert.equal((await author.visit(path, { action: 'hide-comment', comment_id: commentId })).response.status, 404);
await admin.visit(moderation);
assert.equal((await admin.visit(moderation, { action: 'hide-comment', comment_id: commentId })).response.status, 303);
assert.doesNotMatch((await learner.visit(path)).text, /Soal &lt;uji&gt; menarik/);
assert.equal((await author.visit(path, { ...form, action: 'update', title: 'Judul berubah' })).response.status, 409);
assert.equal((await admin.visit('/admin/komunitas/' + id, { action: 'archive', reason: 'Perlu pemeriksaan lanjutan.' })).response.status, 303);
assert.equal((await learner.visit(path)).response.status, 404);
assert.equal((await admin.visit('/admin/komunitas/' + id, { action: 'restore' })).response.status, 303);
assert.match((await learner.visit(path)).text, /Akses diatur melalui antarmuka publik/);
const draft = await author.visit('/komunitas', { ...form, title: 'Draf yang ditolak' });
const draftPath = draft.response.headers.get('location');
const draftMod = '/admin' + draftPath;
const draftRevision = revisionOf(await admin.visit(draftMod));
assert.equal((await admin.visit(draftMod, { action: 'reject', reason: 'Tolong lengkapi pembahasan.', revision: draftRevision })).response.status, 303);
assert.match((await author.visit(draftPath)).text, /Salin untuk revisi/);
assert.equal((await author.visit(draftPath, { action: 'delete' })).response.status, 422);
assert.equal((await author.visit(draftPath, { action: 'delete', confirm: '1' })).response.status, 303);
console.log('PASS: community submission, moderation, practice, voting, comments and archive');
